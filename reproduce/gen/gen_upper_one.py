#!/usr/bin/env python3
"""gen_upper_one.py -- RESEARCH.  Frozen pieces of the ONE-STEP UPPER seed (note section 32), adapted to the quantile-free form.
  x0(s), s = sqrt(a_U): Chebyshev degree 11 (the one-step seed needs x0 far below 5e-5)
  sigma = x0^2 / a_U,  S, Z normalized to [-1, 1],  x = x0 (1 + zeta R(S, Z)),
  R = R0(Z) + S (R1(Z) + S (R2(Z) + S R3)),  row degrees (5, 3, 1, 0): 13 doubles, power/Horner basis,
  fitted in the true L_infinity sense (linear programme) on exact (h, v) samples WITH the polynomial x0, so its error is absorbed.
Writes upper_v031_tables1.hpp.  Needs numpy, scipy, mpmath."""
import math, os, sys, time
import numpy as np
import mpmath as mp
from scipy.optimize import linprog
mp.mp.dps = 40
HERE = os.path.dirname(os.path.abspath(__file__))
V_LO, V_HI, H_HI, W_SEAM = 1.85, 8.0, 16.2, 3.8
def onemC(h, v): return mp.ncdf(-(v / 2 - h / v)) + mp.exp(h) * mp.ncdf(-v / 2 - h / v)
def sample(nx, nw, seed):
    rng = np.random.default_rng(seed); P = []
    for x in np.linspace(V_LO / 2, V_HI / 2, nx):                         # structured (x, W) grid: h = 2 x sqrt(2W) ... W = h^2/(8x^2)
        for W in np.concatenate([np.linspace(0, 3.7999, nw), [1e-6, 1e-4, 1e-2, 3.79, 3.795]]):
            h = 2 * x * math.sqrt(2 * W)
            if 0 < h <= H_HI: P.append((h, 2 * x))
    for _ in range(nx * nw // 2):                                         # boundary-biased random fill
        v = V_LO + (V_HI - V_LO) * rng.random() ** 2; W = 3.7999 * (1 - rng.random() ** 2); h = v * math.sqrt(2 * W)
        if 0 < h <= H_HI: P.append((h, v))
    for v in np.linspace(V_LO, V_HI, 300): P.append((H_HI, v)) if H_HI * H_HI / (2 * v * v) < W_SEAM else None
    out = []
    for h, v in P:
        oc = onemC(mp.mpf(h), mp.mpf(v))
        if oc < mp.mpf(10) ** -15: continue
        out.append((h, v, float(mp.mpf(h) - 2 * mp.log(oc))))
    return np.array(out)
t0 = time.time(); TR = sample(70, 60, 1); VA = sample(97, 83, 2)
print("training %d, validation %d points, %.0f s" % (len(TR), len(VA), time.time() - t0))
AUmin, AUmax = min(TR[:, 2].min(), VA[:, 2].min()), max(TR[:, 2].max(), VA[:, 2].max())
S_LO, S_HI = math.sqrt(AUmin) * 0.995, math.sqrt(AUmax) * 1.005
NX0 = 12
x0_exact = lambda s: -mp.sqrt(2) * mp.erfinv(mp.exp(-mp.mpf(s) ** 2 / 2) - 1)
nodes = [mp.cos(mp.pi * (k + mp.mpf(1) / 2) / NX0) for k in range(NX0)]
fv = [x0_exact((S_LO + S_HI) / 2 + (S_HI - S_LO) / 2 * t) for t in nodes]
X0C = [float((2 if j else 1) * sum(fv[k] * mp.cos(j * mp.pi * (k + mp.mpf(1) / 2) / NX0) for k in range(NX0)) / NX0) for j in range(NX0)]
x0p = lambda s: np.polynomial.chebyshev.chebval((2 * s - (S_LO + S_HI)) / (S_HI - S_LO), X0C)
chk = np.linspace(S_LO, S_HI, 1501); ex = np.array([float(x0_exact(s)) for s in chk])
print("x0(s) degree %d: worst relative error %.2e" % (NX0 - 1, np.max(np.abs(x0p(chk) / ex - 1))))

def coords(D):
    H, V, AU = D[:, 0], D[:, 1], D[:, 2]; X0 = x0p(np.sqrt(AU)); q = H / AU
    return X0, (q / (1 + np.sqrt(1 - q * q))) ** 2, X0 * X0 / AU, V / 2
X0t, Zt, SGt, XT = coords(TR); X0v, Zv, SGv, XV = coords(VA)
SGMIN, SGMAX = float(min(SGt.min(), SGv.min())), float(max(SGt.max(), SGv.max())); ZMAX = float(max(Zt.max(), Zv.max())) * 1.0005
DEG = (5, 3, 1, 0)
def basis(SG, Z):
    S = 2 * (SG - SGMIN) / (SGMAX - SGMIN) - 1; Zn = 2 * Z / ZMAX - 1
    return np.stack([S ** i * Zn ** j for i, d in enumerate(DEG) for j in range(d + 1)], axis=1)
# relative seed error  e = x0 (1 + zeta B c)/x - 1  is affine in c:  e = g + G c
def affine(X0, Z, SG, X): B = basis(SG, Z); return X0 / X - 1, (X0 * Z / X)[:, None] * B
g, G = affine(X0t, Zt, SGt, XT); n = G.shape[1]
cvec = np.zeros(n + 1); cvec[-1] = 1.0
A = np.vstack([np.hstack([G, -np.ones((len(g), 1))]), np.hstack([-G, -np.ones((len(g), 1))])]); b = np.concatenate([-g, g])
res = linprog(cvec, A_ub=A, b_ub=b, bounds=[(None, None)] * n + [(0, None)], method="highs")
assert res.status == 0, res.message
co = res.x[:n]; gv, Gv = affine(X0v, Zv, SGv, XV); ev = np.abs(gv + Gv @ co); k = ev.argmax()
print("13-double seed, rows %s: training max %.4e | validation max %.4e at (h, v, W) = (%.3f, %.3f, %.3f)" % (DEG, res.x[-1], ev.max(), VA[k, 0], VA[k, 1], VA[k, 0] ** 2 / (2 * VA[k, 1] ** 2)))
xv = XV; Wv = VA[:, 0] ** 2 / (2 * VA[:, 1] ** 2); K4 = Wv + Wv ** 2 / 2 - Wv * xv ** 2 / 6 - xv ** 4 / 24
print("quartic predictor of the one-step error (note s32, K4 = W + W^2/2 - W x^2/6 - x^4/24): max %.2e  (max |K4| = %.3f)" % (np.max(np.abs(K4) * ev ** 4), np.abs(K4).max()))
hx = lambda x: float(x).hex()
rows, p = [], 0
for d in DEG: rows.append(co[p:p + d + 1]); p += d + 1
with open(os.path.join(HERE, "upper_v031_tables1.hpp"), "w", newline="\n") as f:
    f.write("// upper_v031_tables1.hpp -- GENERATED by gen_upper_one.py (research).  ONE-STEP seed.  Do not edit.\n#pragma once\nnamespace upper_v031 { namespace one {\n")
    f.write("static const double S_LO = %s, S_HI = %s;\nstatic const int NX0 = %d;\nstatic const double X0C[%d] = { %s };\n" % (hx(S_LO), hx(S_HI), NX0, NX0, ", ".join(hx(c) for c in X0C)))
    f.write("static const double SGMIN = %s, SGMAX = %s, ZMAX = %s;\n" % (hx(SGMIN), hx(SGMAX), hx(ZMAX)))
    for i, r in enumerate(rows): f.write("static const double R%d[%d] = { %s };   // ascending powers of Z\n" % (i, len(r), ", ".join(hx(c) for c in r)))
    f.write("} } // namespace upper_v031::one\n")
print("wrote upper_v031_tables1.hpp")
