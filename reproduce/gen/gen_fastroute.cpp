// gen_fastroute.cpp -- v0.3.1.  The routed seams in the book coordinate.
//   c > ctop(h)  <=>  a < a_top(h) := log1p(expm1(h) / ctop(h)),      c < cw(h)  <=>  a > a_w(h) := log1p(expm1(h) / cw(h)),
// with ctop, cw the FROZEN seam polynomials (br::ctop_price, br::cwstar_price) and a = log1p(expm1(h)/c) the book coordinate.
// Both are smooth one-variable functions of h.  Per band, fit a Chebyshev interpolant of low degree, measure its worst
// deviation on a dense grid, and emit the coefficients together with a margin, so that at runtime
//   a < a_top_fit - margin  =>  certainly above the ceiling,   a > a_top_fit + margin  =>  certainly below,
// and only the sliver in between needs the exact route.  Emits volfi_annulus_fastroute_tables.hpp.
#include <cstdio>
#include <cmath>
#include <vector>
#include <algorithm>
#include "volfi_annulus_all.hpp"
using namespace volfi_annulus;
static double a_of(double h, double c) { return std::log1p(std::expm1(h) / c); }
static double a_top(double h) { return a_of(h, br::ctop_price(h)); }
static double a_w(double h)   { return a_of(h, br::cwstar_price(h)); }
struct Fit { std::vector<double> c; double lo, hi, err; };
template<class F> Fit fit(F f, double lo, double hi, int n) {           // Chebyshev interpolant, n coefficients, on [lo, hi]
    Fit r; r.lo = lo; r.hi = hi; r.c.assign(n, 0.0);
    std::vector<double> fx(n); const double PI = 3.14159265358979323846;
    for (int k = 0; k < n; ++k) { const double t = std::cos(PI * (k + 0.5) / n); fx[k] = f(0.5 * (hi + lo) + 0.5 * (hi - lo) * t); }
    for (int j = 0; j < n; ++j) { double s = 0; for (int k = 0; k < n; ++k) s += fx[k] * std::cos(PI * j * (k + 0.5) / n); r.c[j] = (j == 0 ? 1.0 : 2.0) * s / n; }
    r.err = 0; for (int i = 0; i <= 400000; ++i) { const double h = lo + (hi - lo) * i / 400000.0;
        r.err = std::max(r.err, std::fabs(br::clenshaw1(r.c.data(), n, lo, hi, h) - f(h))); }
    return r;
}
int main() {
    const double bands[4] = { 1e-6, H_ATM_HI, H_BOX, 16.5 };
    std::printf("band          | a_top: deg err (per degree)                      | a_w: deg err\n");
    std::vector<Fit> FT, FW;
    for (int b = 0; b < 3; ++b) {
        std::printf("[%g, %g]\n", bands[b], bands[b + 1]);
        Fit best_t, best_w; best_t.err = best_w.err = 1;
        for (int n = 6; n <= 20; n += 2) { Fit ft = fit(a_top, bands[b], bands[b + 1], n), fw = fit(a_w, bands[b], bands[b + 1], n);
            std::printf("   n=%2d  a_top err %.2e   a_w err %.2e\n", n, ft.err, fw.err);
            if (best_t.err > 1e-9 && ft.err < best_t.err) best_t = ft; if (best_w.err > 1e-9 && fw.err < best_w.err) best_w = fw; }
        FT.push_back(best_t); FW.push_back(best_w);
        double gap = 1e300, mx = 0; for (int i = 0; i <= 400000; ++i) { const double h = bands[b] + (bands[b + 1] - bands[b]) * i / 400000.0; gap = std::min(gap, a_w(h) - a_top(h)); mx = std::max(mx, a_top(h)); }
        std::printf("   chosen: a_top n=%zu err %.2e | a_w n=%zu err %.2e | min(a_w - a_top) = %.4f  max a_top = %.3f\n", best_t.c.size(), best_t.err, best_w.c.size(), best_w.err, gap, mx);
    }
    FILE* o = std::fopen("volfi_annulus_fastroute_tables.hpp", "w");
    std::fprintf(o, "// volfi_annulus_fastroute_tables.hpp -- GENERATED by reproduce/gen/gen_fastroute.cpp.  Routing seams in the book coordinate.\n#pragma once\nnamespace volfi_annulus { namespace fastroute {\n");
    std::fprintf(o, "static const double BAND[4] = { %a, %a, %a, %a };\n", bands[0], bands[1], bands[2], bands[3]);
    auto emit = [&](const char* nm, std::vector<Fit>& F) {
        std::fprintf(o, "static const int    %s_N[3] = { %zu, %zu, %zu };\n", nm, F[0].c.size(), F[1].c.size(), F[2].c.size());
        std::fprintf(o, "static const double %s_M[3] = { %a, %a, %a };   // margin = 4 x worst fit error + 1e-12\n", nm, 4 * F[0].err + 1e-12, 4 * F[1].err + 1e-12, 4 * F[2].err + 1e-12);
        for (int b = 0; b < 3; ++b) { std::fprintf(o, "static const double %s_C%d[%zu] = {", nm, b, F[b].c.size()); for (size_t j = 0; j < F[b].c.size(); ++j) std::fprintf(o, "%s %a", j ? "," : "", F[b].c[j]); std::fprintf(o, " };\n"); }
        std::fprintf(o, "static const double* const %s_C[3] = { %s_C0, %s_C1, %s_C2 };\n", nm, nm, nm, nm); };
    emit("ATOP", FT); emit("AW", FW);
    // band 0 in the price itself: ctop(h) on [1e-6, 0.3] is smooth and O(1), so the routed scalar entry can decide c > ctop(h) without a
    { Fit fc; fc.err = 1; for (int n = 6; n <= 12; n += 2) { Fit f = fit([](double h) { return br::ctop_price(h); }, bands[0], bands[1], n); std::printf("   ctop band 0 n=%d err %.2e\n", n, f.err); if (fc.err > 1e-11 && f.err < fc.err) fc = f; }
      std::fprintf(o, "static const int    CT0_N = %zu;\nstatic const double CT0_M = %a;   // margin on c, absolute\nstatic const double CT0_C[%zu] = {", fc.c.size(), 4 * fc.err + 1e-14, fc.c.size());
      for (size_t j = 0; j < fc.c.size(); ++j) std::fprintf(o, "%s %a", j ? "," : "", fc.c[j]); std::fprintf(o, " };\n"); }
    std::fprintf(o, "} } // namespace volfi_annulus::fastroute\n"); std::fclose(o);
    std::printf("written volfi_annulus_fastroute_tables.hpp\n");
    return 0;
}
